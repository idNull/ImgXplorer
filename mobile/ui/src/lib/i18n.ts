export const lang: "es" | "en" = navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
const dict = lang === "es" ? es : en;
export const t = (k: Key, vars: Record<string, string | number> = {}) =>
  dict[k].replace(/\{(\w+)\}/g, (_, v) => String(vars[v] ?? ""));
