export type Key = keyof (typeof dict)["es"];
export type Lang = keyof typeof dict;
export type LangSetting = Lang | "auto";

const system = (): Lang => (navigator.language.toLowerCase().startsWith("es") ? "es" : "en");
let lang = $state<Lang>(system());

export function setLang(l: LangSetting) {
  lang = l === "auto" ? system() : l;
  document.documentElement.lang = lang;
}

export function currentLang(): Lang {
  return lang;
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return dict[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

/** Etiqueta de plantilla, parámetro u opción; si falta, la propia clave. */
export function label(key: string): string {
  return labels[lang][key] ?? labels.en[key] ?? key.replace(/^\w+\./, "");
}
